"""Bundle T-shirt images into the BEAZER Demo plugin as WooCommerce merch.

usage: python build_merch.py <images_dir> <plugin_dir> [--price 250] [--names names.json]

Every transparent PNG/WebP in <images_dir> (sorted by name) becomes two
square product shots in <plugin_dir>/merch/:
  beazer-tee-NN-black.jpg  on the site's dark red stage (used on the demo)
  beazer-tee-NN-white.jpg  on clean white (store image: cart, checkout, emails)
and merch/products.php lists them for the plugin. Product names come from the
file names unless names.json maps file name -> name.
"""
import argparse
import json
import re
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

SIZE = 1400          # square output
FILL = 0.84          # shirt fills 84% of the frame


def place(tee):
    """Scale the shirt into the frame; returns (rgba, offset)."""
    box = tee.getchannel("A").getbbox() or (0, 0, *tee.size)
    tee = tee.crop(box)
    scale = SIZE * FILL / max(tee.size)
    tee = tee.resize((round(tee.width * scale), round(tee.height * scale)), Image.LANCZOS)
    return tee, ((SIZE - tee.width) // 2, (SIZE - tee.height) // 2 - round(SIZE * 0.01))


def shadow(tee, offset, strength, blur, drop):
    a = Image.new("L", (SIZE, SIZE), 0)
    a.paste(tee.getchannel("A"), (offset[0], offset[1] + drop))
    return a.filter(ImageFilter.GaussianBlur(blur)).point(lambda v: int(v * strength))


def on_white(tee, offset):
    bg = Image.new("RGB", (SIZE, SIZE), (255, 255, 255))
    bg.paste((0, 0, 0), mask=shadow(tee, offset, 0.22, 26, 18))
    bg.paste(tee, offset, tee)
    return bg


def on_black(tee, offset, seed):
    """The site's stage: deep black with a red glow behind the shirt and fine grain."""
    y, x = np.mgrid[0:SIZE, 0:SIZE].astype(np.float32) / SIZE
    glow = np.exp(-(((x - .5) / .42) ** 2 + ((y - .46) / .38) ** 2))
    base = np.array([9, 3, 3], np.float32)
    red = np.array([120, 10, 8], np.float32)
    img = base + glow[..., None] * red
    edge = np.clip(1 - glow * 1.4, 0, 1) ** 2  # darker corners
    img *= (1 - .55 * edge)[..., None]
    rng = np.random.default_rng(seed)
    img += rng.normal(0, 3.2, (SIZE, SIZE, 1))
    bg = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8))
    bg.paste((0, 0, 0), mask=shadow(tee, offset, 0.75, 34, 26))
    bg.paste(tee, offset, tee)
    return bg


def nice_name(stem):
    words = re.sub(r"[_\-]+", " ", stem)
    words = re.sub(r"(?i)\b(beazer|t ?shirts?|tees?|corrected|transparent|final|v\d+)\b", " ", words)
    words = re.sub(r"^\s*\d+\s*|\s+\d+\s*$", " ", words)
    words = " ".join(w.capitalize() if w.islower() else w for w in words.split())
    return f"BEAZER {words} Tee".replace("  ", " ") if words else "BEAZER Tee"


def php_str(value):
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def main(src, plugin, price, names_file):
    names = json.loads(Path(names_file).read_text()) if names_file else {}
    files = sorted(p for p in Path(src).iterdir() if p.suffix.lower() in {".png", ".webp", ".jpg", ".jpeg"})
    out = Path(plugin) / "merch"
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("beazer-tee-*"):
        old.unlink()
    items = []
    for n, f in enumerate(files, 1):
        tee = Image.open(f).convert("RGBA")
        tee, offset = place(tee)
        stem = f"beazer-tee-{n:02d}"
        on_black(tee, offset, n).save(out / f"{stem}-black.jpg", quality=86, optimize=True, progressive=True)
        on_white(tee, offset).save(out / f"{stem}-white.jpg", quality=88, optimize=True, progressive=True)
        name = names.get(f.name) or nice_name(f.stem)
        if any(i["name"] == name for i in items):  # keep product names unique
            name = f"{name} No. {n}"
        items.append({"sku": f"BEAZER-TEE-{n:02d}", "name": name, "black": f"{stem}-black.jpg", "white": f"{stem}-white.jpg"})
        print(f"{f.name} -> {stem}-black/white.jpg  {name}")
    rows = ",\n".join(
        f"\t\tarray( 'sku' => {php_str(i['sku'])}, 'name' => {php_str(i['name'])}, 'black' => {php_str(i['black'])}, 'white' => {php_str(i['white'])} )"
        for i in items
    )
    (out / "products.php").write_text(
        "<?php\n// Generated by tools/build_merch.py: the BEAZER T-shirts sold from /beazertheband/merch/.\n"
        f"return array(\n\t'price' => {php_str(price)},\n\t'items' => array(\n{rows},\n\t),\n);\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("images")
    ap.add_argument("plugin")
    ap.add_argument("--price", default="250")
    ap.add_argument("--names")
    a = ap.parse_args()
    main(a.images, a.plugin, a.price, a.names)
